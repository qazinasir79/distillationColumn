def export_data_js():
    db = CostCorrelationDB()
    df = db.df
    rows = []
    for _, r in df.iterrows():
        rows.append({
            "key": r.get("key"),
            "category": r.get("category"),
            "type": js_num(r.get("type")) if pd.notna(r.get("type")) else None,
            "form": r.get("form"),
            "s_lower": js_num(r.get("s_lower")),
            "s_upper": js_num(r.get("s_upper")),
            "s2_lower": js_num(r.get("s2_lower")),
            "s2_upper": js_num(r.get("s2_upper")),
            "upper_parallel": js_num(r.get("upper_parallel")),
            "a": js_num(r.get("a")), "b": js_num(r.get("b")),
            "n": js_num(r.get("n")), "n2": js_num(r.get("n2")),
            "k1": js_num(r.get("k1")), "k2": js_num(r.get("k2")),
            "k3": js_num(r.get("k3")), "k4": js_num(r.get("k4")),
            "k5": js_num(r.get("k5")),
            "s0": js_num(r.get("s0")), "c0": js_num(r.get("c0")),
            "f": js_num(r.get("f")),
            "cost_year": js_num(r.get("cost_year")),
            "default_material": db.default_material_for_key(r.get("key")),
            "unit": js_num(r.get("unit")) if "unit" in df.columns and pd.notna(r.get("unit")) else None,
        })

    cepci = {str(int(y)): float(v) for y, v in CEPCI_DF["cepci"].items()}

    # FLOW_STRIPS lives in app.py (imports streamlit) -> extract via AST.
    app_src = (ROOT / "app.py").read_text()
    flow_strips = {}
    for node in ast.walk(ast.parse(app_src)):
        if isinstance(node, ast.Assign) and getattr(node.targets[0], "id", "") == "FLOW_STRIPS":
            flow_strips = ast.literal_eval(node.value)

    data = {
        "correlations": rows,
        "cepci": cepci,
        "process_types": Plant.processTypes,
        "loc_factors": Plant.locFactors,
        "macrs": {str(k): [float(x) for x in v] for k, v in _MACRS_HALF_YEAR.items()},
        "equip_process_factors": Equipment.process_factors,
        "material_factors": Equipment.material_factors,
        "presets": json.loads(json.dumps(T.PRESETS, default=str)),
        "learn": {
            "types": json.loads(json.dumps(C.DISTILLATION_TYPES, default=str)),
            "comparison": json.loads(json.dumps(C.COMPARISON_TABLE, default=str)),
            "tips": list(C.GENERAL_TIPS),
            "abbreviations": dict(C.ABBREVIATIONS),
            "flow_strips": flow_strips,
        },
    }
    out = WEBAPP / "js" / "data.js"
    out.write_text(
        "/* AUTO-GENERATED by tools/export_webapp_data.py — DO NOT EDIT. */\n"
        "(function (root) {\n  root.TEA_DATA = "
        + json.dumps(data, allow_nan=False)
        + ";\n})(typeof window !== 'undefined' ? window : globalThis);\n"
    )
    print(f"wrote {out} ({out.stat().st_size/1024:.0f} KB, {len(rows)} correlations)")


